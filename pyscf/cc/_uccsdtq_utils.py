"""Storage and restart helpers for UHF CCSDTQ.

The rank-four blocks follow :mod:`pyscf.cc.uccsdt`'s interleaved
majority-spin convention.  A compact block stores strictly increasing
occupied and virtual indices for each same-spin group.  Mixed-spin groups
remain dense.  Compact UCCSDTQ stores both T3 and T4 in this form.

This module deliberately contains no solver state or global dimensions.  All
sizes are obtained from the CC object passed to a helper, which makes the
conversion functions safe to use from concurrent calculations.
"""

from __future__ import annotations

from itertools import combinations, permutations, product
from math import comb

import numpy as np

from pyscf import lib
from pyscf.lib import logger


def _dims(mycc):
    """Return ``(oa, ob, va, vb)`` after frozen-orbital selection."""
    oa, ob = (int(x) for x in mycc.nocc)
    nma, nmb = (int(x) for x in mycc.nmo)
    return oa, ob, nma - oa, nmb - ob


def _spin_counts(rank):
    # Native UCCSDT order: aaa, aab, bba, bbb (majority spin first).
    return [(na, rank - na) for na in range(rank, -1, -1)]


def _groups(rank, na, nb):
    """Axis groups for a full native block.

    The first two groups are same-spin occupied and virtual indices.  The
    remaining groups are the other spin occupied and virtual indices.  This
    directly describes ``ijabKC`` and ``ijabKLCD`` layouts.
    """
    if na >= nb:
        return (tuple(range(na)), tuple(range(na, 2 * na)),
                tuple(range(2 * na, 2 * na + nb)),
                tuple(range(2 * na + nb, 2 * (na + nb))))
    # Reorder the groups only by spin-majority; native full blocks store the
    # majority-spin groups first even for bba/bbba.
    return (tuple(range(nb)), tuple(range(nb, 2 * nb)),
            tuple(range(2 * nb, 2 * nb + na)),
            tuple(range(2 * nb + na, 2 * (na + nb))))


def _sizes(oa, ob, va, vb, rank, na, nb):
    if na >= nb:
        return oa, va, ob, vb
    return ob, vb, oa, va


def block_shape(mycc, rank, block, compact=False):
    """Return the expected shape of a native UHF block.

    ``block`` is the zero-based spin block in the order generated by
    :func:`_spin_counts`.  For compact storage, same-spin groups are replaced
    by ``C(n, rank)``; mixed-spin singleton groups remain dense.
    """
    oa, ob, va, vb = _dims(mycc)
    na, nb = _spin_counts(rank)[block]
    nocc1, nvir1, nocc2, nvir2 = _sizes(oa, ob, va, vb, rank, na, nb)
    r1, r2 = max(na, nb), min(na, nb)
    if not compact:
        return ((nocc1,) * r1 + (nvir1,) * r1 +
                (nocc2,) * r2 + (nvir2,) * r2)
    out = []
    if r1:
        out.extend((comb(nocc1, r1), comb(nvir1, r1)))
    if r2:
        out.extend((comb(nocc2, r2), comb(nvir2, r2)))
    return tuple(out)


def _is_compact(arr, shape):
    return tuple(arr.shape) == tuple(shape)


def _group_values(n, rank):
    return tuple(combinations(range(n), rank))


def _canonical_groups(mycc, rank, block):
    oa, ob, va, vb = _dims(mycc)
    na, nb = _spin_counts(rank)[block]
    nocc1, nvir1, nocc2, nvir2 = _sizes(oa, ob, va, vb, rank, na, nb)
    groups = _groups(rank, na, nb)
    r1, r2 = max(na, nb), min(na, nb)
    ns = (nocc1, nvir1, nocc2, nvir2)
    vals = []
    kept_groups = []
    for g, n, r in zip(groups, ns, (r1, r1, r2, r2)):
        if r:
            kept_groups.append(g)
            vals.append(_group_values(n, r) if r > 1 else tuple((i,) for i in range(n)))
    return tuple(kept_groups), vals, (na, nb)


def _perm_sign(p):
    return -1 if sum(p[i] > p[j] for i in range(len(p)) for j in range(i + 1, len(p))) & 1 else 1


def _combination_indices(groups, values, placements=None):
    """Broadcast one-dimensional combination columns into compact shape.

    Unlike a meshgrid over full orbital tuples, these indices need memory
    proportional to the *sum* of group combination counts.
    """
    index = []
    for axis, (group, vals) in enumerate(zip(groups, values)):
        combos = np.asarray(vals, dtype=np.intp).reshape(-1, len(group))
        shape = [1] * len(groups)
        shape[axis] = len(combos)
        placement = range(len(group)) if placements is None else placements[axis]
        index.extend(combos[:, i].reshape(shape) for i in placement)
    return tuple(index)


def _pack_block(mycc, full, rank, block):
    expected = block_shape(mycc, rank, block, compact=True)
    full = np.asarray(full)
    if _is_compact(full, expected):
        return np.array(full, copy=True)
    full_shape = block_shape(mycc, rank, block, compact=False)
    if tuple(full.shape) != tuple(full_shape):
        raise ValueError('block %d rank-%d shape %s, expected full %s or compact %s' %
                         (block, rank, full.shape, full_shape, expected))
    groups, vals, _ = _canonical_groups(mycc, rank, block)
    return full[_combination_indices(groups, vals)]


def _unpack_block(mycc, packed, rank, block):
    expected = block_shape(mycc, rank, block, compact=True)
    packed = np.asarray(packed)
    if tuple(packed.shape) != tuple(expected):
        full_shape = block_shape(mycc, rank, block, compact=False)
        if tuple(packed.shape) == tuple(full_shape):
            return np.array(packed, copy=True)
        raise ValueError('block %d rank-%d shape %s, expected compact %s or full %s' %
                         (block, rank, packed.shape, expected, full_shape))
    full_shape = block_shape(mycc, rank, block, compact=False)
    out = np.zeros(full_shape, dtype=packed.dtype)
    groups, vals, _ = _canonical_groups(mycc, rank, block)
    base_index = _combination_indices(groups, vals)
    patterns = []
    for group in groups:
        perms = tuple(permutations(range(len(group))))
        patterns.append(tuple((p, _perm_sign(p)) for p in perms))
    # Scatter an entire packed block for each independent same-spin
    # permutation. There is no Python loop over individual amplitudes.
    for choices in product(*patterns):
        placements, signs = zip(*choices)
        sign = np.prod(signs)
        permuted_index = tuple(base_index[g[p]] for g, order in zip(groups, placements) for p in order)
        out[permuted_index] = sign * packed
    return out


def pack_blocks(mycc, blocks, rank):
    """Pack a rank ``rank`` block list into unique native coordinates."""
    if len(blocks) != rank + 1:
        raise ValueError('rank-%d requires %d spin blocks' % (rank, rank + 1))
    return tuple(_pack_block(mycc, x, rank, i) for i, x in enumerate(blocks))


def unpack_blocks(mycc, blocks, rank):
    """Expand a rank ``rank`` block list to full native tensors."""
    if len(blocks) != rank + 1:
        raise ValueError('rank-%d requires %d spin blocks' % (rank, rank + 1))
    if rank == 4:
        size = sum(int(np.prod(block_shape(mycc, rank, b, False), dtype=np.int64)) * np.asarray(x).itemsize
                   for b, x in enumerate(blocks))
        available = max(0, getattr(mycc, 'max_memory', np.inf) - lib.current_memory()[0]) * 1e6
        if size > available:
            raise MemoryError('Full T4 expansion needs %.1f MB; only %.1f MB remains in max_memory' %
                              (size / 1e6, available / 1e6))
    return tuple(_unpack_block(mycc, x, rank, i) for i, x in enumerate(blocks))


def pack_t4(mycc, blocks):
    """Pack ``aaaa, aaab, aabb, bbba, bbbb`` T4 blocks."""
    return pack_blocks(mycc, blocks, 4)


def unpack_t4(mycc, blocks):
    """Expand compact T4 blocks to full ``aaaa, aaab, aabb, bbba, bbbb``."""
    return unpack_blocks(mycc, blocks, 4)


def packed_index(coords, n):
    """Return the lexicographic index of a strictly increasing tuple."""
    coords = tuple(int(x) for x in coords)
    if any(x < 0 or x >= n for x in coords) or any(a >= b for a, b in zip(coords, coords[1:])):
        raise ValueError('coordinates must be strictly increasing and in range')
    rank = len(coords)
    # Number of combinations preceding this one in lexicographic order.
    idx = 0
    lo = 0
    for pos, x in enumerate(coords):
        for y in range(lo, x):
            idx += comb(n - y - 1, rank - pos - 1)
        lo = x + 1
    return idx


def packed_get(block, coordinates, sizes=None):
    """Get an element by packed coordinates.

    ``coordinates`` may already contain packed integer coordinates.  If
    ``sizes`` is supplied, each coordinate is instead a canonical increasing
    tuple and is converted with :func:`packed_index`.
    """
    if sizes is not None:
        coordinates = tuple(packed_index(c, n) for c, n in zip(coordinates, sizes))
    return block[tuple(int(c) for c in coordinates)]


def packed_set(block, coordinates, value, sizes=None):
    """Set an element by packed or canonical coordinates (see packed_get)."""
    if sizes is not None:
        coordinates = tuple(packed_index(c, n) for c, n in zip(coordinates, sizes))
    block[tuple(int(c) for c in coordinates)] = value


def _compact_block_for_vector(mycc, arr, rank, block):
    arr = np.asarray(arr)
    return _pack_block(mycc, arr, rank, block)


def amplitudes_to_vector(mycc, tamps):
    """Flatten all supplied ranks in unique-coordinate order.

    As in UCCSDT, the caller selects the ranks. The iteration driver passes
    T1--T3 when T4 is excluded from DIIS.
    """
    if tamps is None:
        tamps = mycc.tamps
    cc_order = int(getattr(mycc, 'cc_order', len(tamps)))
    max_rank = min(cc_order, len(tamps))
    chunks = []
    dtype = None
    for rank in range(1, max_rank + 1):
        blocks = tamps[rank - 1]
        for block in range(rank + 1):
            shape = block_shape(mycc, rank, block, compact=True)
            if blocks is None or block >= len(blocks):
                arr = np.zeros(shape, dtype=float)
            else:
                arr = _compact_block_for_vector(mycc, blocks[block], rank, block)
            dtype = arr.dtype if dtype is None else np.result_type(dtype, arr.dtype)
            chunks.append(np.asarray(arr).ravel())
    if not chunks:
        return np.empty(0, dtype=float)
    return np.concatenate(chunks).astype(dtype, copy=False)


def vector_size(mycc, include_t4=True):
    """Unique elements of all ranks, or T1--T3 with ``include_t4=False``."""
    max_rank = min(int(getattr(mycc, 'cc_order', 4)), 4 if include_t4 else 3)
    return sum(int(np.prod(block_shape(mycc, rank, block, compact=True), dtype=np.int64))
               for rank in range(1, max_rank + 1) for block in range(rank + 1))


def vector_to_amplitudes(mycc, vector):
    """Reconstruct full T1/T2 and compact/full T3/T4 from a DIIS vector."""
    vector = np.asarray(vector)
    sizes = [0]
    cc_order = int(getattr(mycc, 'cc_order', 4))
    for rank in range(1, cc_order + 1):
        sizes.append(sizes[-1] + sum(int(np.prod(block_shape(mycc, rank, b, True), dtype=np.int64))
                                     for b in range(rank + 1)))
    matches = [rank for rank in range(1, cc_order + 1) if sizes[rank] == vector.size]
    if not matches:
        raise ValueError('Mismatch between vector size (%d) and amplitude ranks' % vector.size)
    preferred = cc_order if getattr(mycc, 'do_diis_max_t', False) else cc_order - 1
    max_rank = preferred if preferred in matches else max(matches)
    tamps = []
    offset = 0
    for rank in range(1, max_rank + 1):
        compact = []
        for block in range(rank + 1):
            shape = block_shape(mycc, rank, block, compact=True)
            n = int(np.prod(shape, dtype=np.int64))
            compact.append(vector[offset:offset + n].reshape(shape).copy())
            offset += n
        if rank < 3 or not getattr(mycc, 'do_tri_max_t', False):
            tamps.append(unpack_blocks(mycc, compact, rank))
        else:
            tamps.append(tuple(compact))
    return tamps


def memory_estimate(mycc, diis_space=None, include_t4_diis=None):
    """Return component-wise resident-memory estimates in bytes and GB.

    The estimate intentionally reports components separately; allocator and
    contraction temporaries are not folded into a misleading hard process cap.
    """
    oa, ob, va, vb = _dims(mycc)
    itemsize = np.dtype(getattr(mycc, 'dtype', np.float64)).itemsize
    cc_order = min(int(getattr(mycc, 'cc_order', 4)), 4)
    include_t4 = bool(getattr(mycc, 'do_diis_max_t', False)) if include_t4_diis is None else bool(include_t4_diis)
    parts = {}
    for rank in range(1, cc_order + 1):
        compact = rank >= 3 and getattr(mycc, 'do_tri_max_t', True)
        count = sum(int(np.prod(block_shape(mycc, rank, b, compact), dtype=np.int64))
                    for b in range(rank + 1))
        parts['T%d' % rank] = count * itemsize
    for rank in range(1, cc_order + 1):
        parts['R%d' % rank] = parts['T%d' % rank]
    nma, nmb = oa + va, ob + vb
    eri = nma**4 + nma**2 * nmb**2 + nmb**4
    parts['bare_eris'] = eri * itemsize
    parts['dressed_eris'] = eri * itemsize
    if diis_space is None:
        diis_space = int(getattr(mycc, 'diis_space', 0))
    lower = itemsize * sum(int(np.prod(block_shape(mycc, rank, block, True), dtype=np.int64))
                           for rank in range(1, min(cc_order, 3) + 1) for block in range(rank + 1))
    parts['DIIS'] = 2 * int(diis_space) * lower
    if include_t4:
        unique_t4 = itemsize * sum(int(np.prod(block_shape(mycc, 4, b, True), dtype=np.int64)) for b in range(5))
        parts['DIIS'] += 2 * int(diis_space) * unique_t4
    parts['total_components'] = sum(parts.values())
    parts['gb'] = {key: value / 1e9 for key, value in parts.items() if key != 'gb'}
    return parts


def memory_estimate_log(mycc, diis_space=None, include_t4_diis=None):
    parts = memory_estimate(mycc, diis_space, include_t4_diis)
    log = logger.new_logger(mycc)
    log.info('UCCSDTQ storage estimate (components, not a hard RSS cap)')
    for key, value in parts['gb'].items():
        log.info('  %-18s %10.4f GB', key, value)
    return parts


def _checkpoint_group(mycc):
    return 'uccsdtq_highm' if not getattr(mycc, 'do_tri_max_t', True) else 'uccsdtq'


def dump_chk(mycc, tamps=None, frozen=None, mo_coeff=None, mo_occ=None):
    """Save amplitudes and metadata under a UCCSDTQ-specific checkpoint group."""
    if not getattr(mycc, 'chkfile', None):
        return mycc
    if tamps is None:
        tamps = getattr(mycc, 'tamps', None)
    if frozen is None:
        frozen = getattr(mycc, 'frozen', None)
    payload = {
        'order': int(getattr(mycc, 'cc_order', 4)),
        'storage': 'compact' if getattr(mycc, 'do_tri_max_t', True) else 'full',
        'do_diis_max_t': bool(getattr(mycc, 'do_diis_max_t', False)),
        'nocc': tuple(mycc.nocc),
        'nmo': tuple(mycc.nmo),
        'e_corr': getattr(mycc, 'e_corr', 0.0),
        'tamps': tamps,
        'frozen': 0 if frozen is None else frozen,
    }
    if mo_coeff is not None:
        payload['mo_coeff'] = mo_coeff
    if mo_occ is not None:
        payload['mo_occ'] = mo_occ
    if getattr(mycc, '_nmo', None) is not None:
        payload['_nmo'] = mycc._nmo
    if getattr(mycc, '_nocc', None) is not None:
        payload['_nocc'] = mycc._nocc
    lib.chkfile.save(mycc.chkfile, _checkpoint_group(mycc), payload)
    return mycc


def load_chk(chkfile, mycc=None, group=None):
    """Load a UCCSDTQ checkpoint payload, optionally binding it to ``mycc``."""
    if group is None:
        group = 'uccsdtq'
    try:
        payload = lib.chkfile.load(chkfile, group)
    except (KeyError, OSError):
        payload = None
    if payload is None and group != 'uccsdtq_highm':
        payload = lib.chkfile.load(chkfile, 'uccsdtq_highm')
    if payload is None:
        raise ValueError('No UCCSDTQ checkpoint group found in %s' % chkfile)
    for key in ('storage',):
        if isinstance(payload.get(key), bytes):
            payload[key] = payload[key].decode()
    if mycc is not None:
        if int(payload.get('order', 4)) != int(getattr(mycc, 'cc_order', 4)):
            raise ValueError('Checkpoint coupled-cluster order does not match target object')
        for key in ('nocc', 'nmo'):
            if key in payload and tuple(payload[key]) != tuple(getattr(mycc, key)):
                raise ValueError('Checkpoint %s does not match target active space' % key)
        tamps = payload.get('tamps')
        if tamps is not None:
            tamps = list(tamps)
            convert = pack_blocks if getattr(mycc, 'do_tri_max_t', True) else unpack_blocks
            # Older compact checkpoints only packed T4. Convert each rank
            # from its actual shape, rather than relying on the storage tag.
            for rank in (3, 4):
                if len(tamps) >= rank and tamps[rank - 1] is not None:
                    tamps[rank - 1] = convert(mycc, tamps[rank - 1], rank)
            mycc.tamps = tamps
        if 'e_corr' in payload:
            mycc.e_corr = payload['e_corr']
    return payload


def restore_from_diis_(mycc, diis_file, inplace=True):
    """Restore a UCCSDTQ DIIS history, preserving T4 when DIIS excludes it."""
    adiis = lib.diis.DIIS(mycc, getattr(mycc, 'diis_file', None),
                          incore=getattr(mycc, 'incore_complete', False))
    adiis.restore(diis_file, inplace=inplace)
    vector = adiis.extrapolate()
    tamps = vector_to_amplitudes(mycc, vector)
    if not getattr(mycc, 'do_diis_max_t', False):
        old = getattr(mycc, 'tamps', None)
        if old is not None and len(old) == 4 and old[3] is not None:
            t4 = old[3]
        else:
            t4 = tuple(np.zeros(block_shape(mycc, 4, b, getattr(mycc, 'do_tri_max_t', True)), dtype=vector.dtype)
                       for b in range(5))
        tamps.append(t4)
    mycc.tamps = tamps
    if inplace:
        mycc.diis = adiis
    return mycc


# Explicit aliases make binding from a solver class clear and stable.
amplitudes_to_vector_uhf = amplitudes_to_vector
vector_to_amplitudes_uhf = vector_to_amplitudes
vector_size_uhf = vector_size
memory_estimate_uccsdtq = memory_estimate
